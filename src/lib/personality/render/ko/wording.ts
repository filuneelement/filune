export function traitPhrase(trait: string): string | undefined {
  const value = trait.trim()
  const explicit = phrases.get(value)
  if (explicit) return isCustomerSafeKo(explicit) ? explicit : undefined
  if (!value || !isCustomerSafeKo(value) || /[.!?\n]/u.test(value)) return undefined
  // The registry uses normalized Korean nominal phrases and nominalized verbs.
  const endings: ReadonlyArray<readonly [RegExp, string]> = [
    [/기 쉬움$/u, '기 쉬운'], [/수 있음$/u, '수 있는'], [/어려움$/u, '어려운'],
    [/쉬움$/u, '쉬운'], [/빠름$/u, '빠른'], [/적임$/u, '적인'],
    [/강해짐$/u, '강해지는'], [/줄어듦$/u, '줄어드는'], [/드러남$/u, '드러나는'],
    [/더해짐$/u, '더해지는'], [/커짐$/u, '커지는'], [/걸림$/u, '걸리는'],
    [/냉정해짐$/u, '냉정해지는'], [/떨어짐$/u, '떨어지는'], [/뚜렷해짐$/u, '뚜렷해지는'],
    [/나타남$/u, '나타나는'], [/두드러짐$/u, '두드러지는'], [/드러냄$/u, '드러내는'],
    [/줄임$/u, '줄이는'], [/누그러뜨림$/u, '누그러뜨리는'], [/지침$/u, '지치는'],
    [/기다림$/u, '기다리는'], [/따름$/u, '따르는'], [/고름$/u, '고르는'],
    [/버팀$/u, '버티는'], [/모음$/u, '모으는'], [/기울임$/u, '기울이는'],
    [/옮겨감$/u, '옮겨가는'], [/들어봄$/u, '들어보는'], [/바꿈$/u, '바꾸는'],
    [/넘어감$/u, '넘어가는'], [/익힘$/u, '익히는'], [/줌$/u, '주는'],
    [/잡음$/u, '잡는'], [/보임$/u, '보이는'], [/둠$/u, '두는'],
    [/지냄$/u, '지내는'], [/찾음$/u, '찾는'], [/꺼림$/u, '꺼리는'], [/품음$/u, '품는'],
    [/하지 않음$/u, '하지 않는'], [/챙김$/u, '챙기는'], [/쌓음$/u, '쌓는'],
    [/움직임$/u, '움직이는'], [/지킴$/u, '지키는'], [/느낌$/u, '느끼는'],
    [/살핌$/u, '살피는'], [/삼킴$/u, '삼키는'], [/털어놓음$/u, '털어놓는'],
    [/웃어넘김$/u, '웃어넘기는'], [/밝힘$/u, '밝히는'], [/돌아봄$/u, '돌아보는'],
    [/쓰임$/u, '쓰이는'], [/삼음$/u, '삼는'], [/답함$/u, '답하는'],
    [/(꼼꼼|치밀|성실|엄격|정확|익숙|단호|온화|원만|솔직|신중|차분|민감|유연|정직)함$/u, '$1한'],
    [/함$/u, '하는'],
    [/없음$/u, '없는'], [/있음$/u, '있는'], [/않음$/u, '않는'],
    [/선호$/u, '을 선호하는'], [/중시$/u, '을 중시하는'],
  ]
  for (const [ending, replacement] of endings) {
    if (ending.test(value)) {
      if (replacement.startsWith('을 ')) {
        const object = value.replace(ending, '').trimEnd()
        return object + particle(object, '을', '를') + replacement.slice(1)
      }
      return value.replace(ending, replacement)
    }
  }
  const topic = value.replace(/ (?:경향|성향|편)$/u, '')
  if (topic !== value) return topic
  if (/(?:하는|되는|있는|없는|않는|이어가는|여기는|보이는|드러나는)$/u.test(value)) return value
  return value + particle(value, '을', '를') + ' 보이는'
}

function particle(word: string, withFinal: string, withoutFinal: string) {
  const code = word.charCodeAt(word.length - 1)
  return code >= 0xac00 && code <= 0xd7a3 && (code - 0xac00) % 28 ? withFinal : withoutFinal
}
