C. 영어 localization style guide
영어 내부 용어는 영어권 BaZi 자료에서 널리 쓰이는 표기(Day Master, Ten Gods, Luck Pillar 등)를 따르되, 학파마다 다른 동의어는 하나로 고정한다. 고객 문장은 이 용어를 쓰지 않고 평이한 영어로 풀어 쓴다.
