B. 일본어 localization style guide
일본어 고객 문장은 현대 일본어의 자연스러운 구어로 쓰고, 명리 용어 대신 자연의 모습과 작용을 풀어 쓴다. 각 항목 옆의 W 번호는 대응하는 한국어 규칙(문서 B)이다.
